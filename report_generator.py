# -*- coding: utf-8 -*-
"""AI股神团队 - 报告生成器：将分析会话转换为精美的 HTML 报告。

1.0 起按职责拆分，本文件保留 HTMLReportGenerator 本体：

    report_styles.py    REPORT_CSS —— 全部 CSS（原占本文件 450+ 行）
    report_markdown.py  markdown_to_html() —— 轻量 Markdown 转换（纯函数）
    report_generator.py 本文件：各章节生成 + 拼装 + 保存
"""

import os
from typing import Optional

from orchestrator import AnalysisSession
from report_markdown import markdown_to_html
from report_styles import REPORT_CSS


class HTMLReportGenerator:
    """HTML报告生成器"""

    def __init__(self, session: AnalysisSession):
        self.session = session
        self.stock_code = session.stock_code
        self.company_name = session.company_name
        self.session_id = session.session_id
        self.created_at = session.created_at

    def generate(self) -> str:
        """生成完整HTML报告"""
        html_parts = [
            self._generate_header(),
            self._generate_styles(),
            "</head><body>",
            self._generate_cover(),
            self._generate_toc(),
            self._generate_executive_summary(),
            self._generate_analyst_reports(),
            self._generate_research_debate(),
            self._generate_trade_decision(),
            self._generate_risk_assessment(),
            self._generate_footer(),
            self._generate_scripts(),
            "</body></html>"
        ]
        return "\n".join(html_parts)
    
    def _generate_header(self) -> str:
        return f'''<!-- Generated by Trae Work -->
<!DOCTYPE html>
<html lang="zh-CN">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>AI股神分析报告 - {self.stock_code}</title>
    <link rel="preconnect" href="https://fonts.googleapis.com">
    <link href="https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@300;400;500;700;900&display=swap" rel="stylesheet">
'''

    def _generate_styles(self) -> str:
        """返回完整 <style> 块（样式定义见 report_styles.REPORT_CSS）。"""
        return REPORT_CSS

    def _generate_cover(self) -> str:
        # 注：此处原有一段 final_rec / verdict_class 计算，但封面 HTML 从未引用二者
        # （裁决展示在 _generate_decision 内），属死代码，已移除。输出不变。
        return f'''
        <div class="cover">
            <div class="cover-content">
                <div class="cover-badge">AI股神团队分析报告</div>
                <div class="cover-stock">{self.stock_code}</div>
                <div class="cover-company">{self.company_name}</div>
                <div class="cover-meta">
                    <span>📅 {self.created_at}</span>
                    <span>🔍  session ID: {self.session_id}</span>
                    <span>📊 8维度深度分析</span>
                </div>
            </div>
            <div class="scroll-indicator">⬇️</div>
        </div>'''
    
    def _generate_toc(self) -> str:
        toc_items = [
            ("📋", "执行摘要", "核心结论与投资建议", "#executive-summary"),
            ("📊", "基本面分析", "财务状况与估值评估", "#fundamental"),
            ("🗣️", "情绪分析", "市场情绪与舆情监测", "#sentiment"),
            ("📰", "新闻分析", "宏观事件与公司动态", "#news"),
            ("📈", "技术分析", "价格行为与技术指标", "#technical"),
            ("🐂", "看多论证", "买入理由与增长逻辑", "#bullish"),
            ("🐻", "看空论证", "风险识别与避险逻辑", "#bearish"),
            ("🧑‍💼", "交易决策", "综合研判与策略制定", "#trade"),
            ("🛡️", "风控审批", "风险评估与最终决策", "#risk"),
        ]
        
        items_html = "\n".join([
            f'<a href="{href}" class="toc-item">'
            f'<div class="toc-emoji">{emoji}</div>'
            f'<div class="toc-text"><h3>{title}</h3><p>{desc}</p></div>'
            f'</a>'
            for emoji, title, desc, href in toc_items
        ])
        
        return f'''
        <div class="toc">
            <h2>📑 报告目录</h2>
            <div class="toc-grid">
                {items_html}
            </div>
        </div>'''
    
    def _generate_executive_summary(self) -> str:
        # 收集所有评分
        scores = []
        if self.session.analyst_reports:
            for report in self.session.analyst_reports.values():
                if report.score is not None:
                    scores.append(report.score)
        
        avg_score = sum(scores) / len(scores) if scores else 0
        
        # 确定最终建议
        final_rec = "分析中..."
        risk_score = "N/A"
        if self.session.final_decision:
            final_rec = self.session.final_decision.recommendation or "待定"
            risk_score = str(self.session.final_decision.score or "N/A")
        
        verdict_class = "hold"
        if "买" in final_rec or "Buy" in final_rec:
            verdict_class = "buy"
        elif "卖" in final_rec or "Sell" in final_rec:
            verdict_class = "sell"
        
        return f'''
        <div class="section exec-summary" id="executive-summary">
            <div class="section-header">
                <div class="section-emoji">📋</div>
                <div class="section-title-group">
                    <h2>执行摘要</h2>
                    <p>Executive Summary - 核心结论与投资建议</p>
                </div>
            </div>
            
            <div class="decision-box">
                <div class="decision-verdict {verdict_class}">{final_rec}</div>
                <p style="color: var(--muted);">AI股神团队综合研判结果</p>
            </div>
            
            <div class="summary-grid">
                <div class="summary-stat">
                    <div class="summary-stat-value score-high">{avg_score:.1f}</div>
                    <div class="summary-stat-label">综合评分 (1-10)</div>
                </div>
                <div class="summary-stat">
                    <div class="summary-stat-value">{len(scores)}</div>
                    <div class="summary-stat-label">分析维度</div>
                </div>
                <div class="summary-stat">
                    <div class="summary-stat-value score-medium">{risk_score}</div>
                    <div class="summary-stat-label">风险等级 (1-10)</div>
                </div>
                <div class="summary-stat">
                    <div class="summary-stat-value">{self.stock_code}</div>
                    <div class="summary-stat-label">分析标的</div>
                </div>
            </div>
        </div>'''
    
    def _generate_analyst_reports(self) -> str:
        sections = []
        
        # 基本面
        if "analyst_fundamental" in self.session.analyst_reports:
            report = self.session.analyst_reports["analyst_fundamental"]
            sections.append(self._generate_report_card("fundamental", "📊", "基本面分析",
                "Fundamental Analysis - 财务状况与估值评估", report))
        
        # 情绪
        if "analyst_sentiment" in self.session.analyst_reports:
            report = self.session.analyst_reports["analyst_sentiment"]
            sections.append(self._generate_report_card("sentiment", "🗣️", "情绪分析",
                "Sentiment Analysis - 市场情绪与舆情监测", report))
        
        # 新闻
        if "analyst_news" in self.session.analyst_reports:
            report = self.session.analyst_reports["analyst_news"]
            sections.append(self._generate_report_card("news", "📰", "新闻分析",
                "News Analysis - 宏观事件与公司动态", report))
        
        # 技术
        if "analyst_technical" in self.session.analyst_reports:
            report = self.session.analyst_reports["analyst_technical"]
            sections.append(self._generate_report_card("technical", "📈", "技术分析",
                "Technical Analysis - 价格行为与技术指标", report))
        
        return "\n".join(sections)
    
    def _generate_report_card(self, section_id: str, emoji: str, title: str,
                             subtitle: str, report) -> str:
        score = report.score
        score_class = "score-medium"
        if score is not None:
            if score >= 7:
                score_class = "score-high"
            elif score <= 4:
                score_class = "score-low"
        
        rec = report.recommendation or ""
        badge_class = "badge-neutral"
        if "买" in rec or "Buy" in rec or "强烈买入" in rec:
            badge_class = "badge-buy"
        elif "卖" in rec or "Sell" in rec or "强烈卖出" in rec:
            badge_class = "badge-sell"
        elif "持有" in rec or "Hold" in rec:
            badge_class = "badge-hold"
        
        # 将markdown内容转换为HTML
        content_html = self._markdown_to_html(report.content)
        
        return f'''
        <div class="section" id="{section_id}">
            <div class="section-header">
                <div class="section-emoji">{emoji}</div>
                <div class="section-title-group">
                    <h2>{title}</h2>
                    <p>{subtitle}</p>
                </div>
            </div>
            
            <div class="card">
                <div class="card-header">
                    <div class="card-agent">
                        <div class="card-agent-emoji">{report.agent_emoji}</div>
                        <div>
                            <div class="card-agent-name">{report.agent_name}</div>
                            <div class="card-agent-role">{report.timestamp}</div>
                        </div>
                    </div>
                    <div class="card-score">
                        <div class="score-value {score_class}">{score if score is not None else '-'}/10</div>
                        <div class="score-label">评分</div>
                    </div>
                </div>
                <div class="card-content">
                    {content_html}
                </div>
                <div class="signal-badges">
                    <span class="badge {badge_class}">{rec if rec else '待定'}</span>
                </div>
            </div>
        </div>'''
    
    def _generate_research_debate(self) -> str:
        bullish_html = ""
        bearish_html = ""
        
        if self.session.bullish_report:
            report = self.session.bullish_report
            score = report.score
            score_class = "score-high" if score and score >= 7 else "score-medium"
            content = self._markdown_to_html(report.content)
            bullish_html = f'''
            <div class="card">
                <div class="card-header">
                    <div class="card-agent">
                        <div class="card-agent-emoji">🐂</div>
                        <div>
                            <div class="card-agent-name">{report.agent_name}</div>
                            <div class="card-agent-role">多头论证</div>
                        </div>
                    </div>
                    <div class="card-score">
                        <div class="score-value {score_class}">{score if score is not None else '-'}/10</div>
                        <div class="score-label">看多强度</div>
                    </div>
                </div>
                <div class="card-content">
                    {content}
                </div>
            </div>'''
        
        if self.session.bearish_report:
            report = self.session.bearish_report
            score = report.score
            score_class = "score-danger" if score and score >= 7 else "score-medium"
            content = self._markdown_to_html(report.content)
            bearish_html = f'''
            <div class="card">
                <div class="card-header">
                    <div class="card-agent">
                        <div class="card-agent-emoji">🐻</div>
                        <div>
                            <div class="card-agent-name">{report.agent_name}</div>
                            <div class="card-agent-role">空头论证</div>
                        </div>
                    </div>
                    <div class="card-score">
                        <div class="score-value {score_class}">{score if score is not None else '-'}/10</div>
                        <div class="score-label">看空强度</div>
                    </div>
                </div>
                <div class="card-content">
                    {content}
                </div>
            </div>'''
        
        return f'''
        <div class="section" id="bullish">
            <div class="section-header">
                <div class="section-emoji">🐂</div>
                <div class="section-title-group">
                    <h2>看多论证</h2>
                    <p>Bullish Case - 买入理由与增长逻辑</p>
                </div>
            </div>
            {bullish_html}
        </div>
        
        <div class="section" id="bearish">
            <div class="section-header">
                <div class="section-emoji">🐻</div>
                <div class="section-title-group">
                    <h2>看空论证</h2>
                    <p>Bearish Case - 风险识别与避险逻辑</p>
                </div>
            </div>
            {bearish_html}
        </div>'''
    
    def _generate_trade_decision(self) -> str:
        if not self.session.trade_proposal:
            return ""
        
        report = self.session.trade_proposal
        content = self._markdown_to_html(report.content)
        
        rec = report.recommendation or ""
        badge_class = "badge-neutral"
        if "买" in rec or "Buy" in rec:
            badge_class = "badge-buy"
        elif "卖" in rec or "Sell" in rec:
            badge_class = "badge-sell"
        elif "持有" in rec or "Hold" in rec:
            badge_class = "badge-hold"
        
        return f'''
        <div class="section" id="trade">
            <div class="section-header">
                <div class="section-emoji">🧑‍💼</div>
                <div class="section-title-group">
                    <h2>交易决策</h2>
                    <p>Trading Decision - 综合研判与策略制定</p>
                </div>
            </div>
            
            <div class="card">
                <div class="card-header">
                    <div class="card-agent">
                        <div class="card-agent-emoji">🧑‍💼</div>
                        <div>
                            <div class="card-agent-name">{report.agent_name}</div>
                            <div class="card-agent-role">首席交易员</div>
                        </div>
                    </div>
                    <div class="card-score">
                        <div class="score-value">{report.score if report.score is not None else '-'}/10</div>
                        <div class="score-label">信心评分</div>
                    </div>
                </div>
                <div class="card-content">
                    {content}
                </div>
                <div class="signal-badges">
                    <span class="badge {badge_class}">{rec if rec else '待定'}</span>
                </div>
            </div>
        </div>'''
    
    def _generate_risk_assessment(self) -> str:
        if not self.session.final_decision:
            return ""
        
        report = self.session.final_decision
        content = self._markdown_to_html(report.content)
        
        score = report.score
        score_class = "score-low"
        if score is not None:
            if score <= 3:
                score_class = "score-high"
            elif score <= 6:
                score_class = "score-medium"
        
        rec = report.recommendation or ""
        
        return f'''
        <div class="section final-decision" id="risk">
            <div class="section-header">
                <div class="section-emoji">🛡️</div>
                <div class="section-title-group">
                    <h2>风控审批</h2>
                    <p>Risk Assessment & Final Decision - 风险评估与最终决策</p>
                </div>
            </div>
            
            <div class="card">
                <div class="card-header">
                    <div class="card-agent">
                        <div class="card-agent-emoji">🛡️</div>
                        <div>
                            <div class="card-agent-name">{report.agent_name}</div>
                            <div class="card-agent-role">风控官 & 投资经理</div>
                        </div>
                    </div>
                    <div class="card-score">
                        <div class="score-value {score_class}">{score if score is not None else '-'}/10</div>
                        <div class="score-label">风险等级</div>
                    </div>
                </div>
                <div class="card-content">
                    {content}
                </div>
                <div class="signal-badges">
                    <span class="badge badge-neutral">{rec if rec else '待定'}</span>
                </div>
            </div>
        </div>'''
    
    def _generate_footer(self) -> str:
        return f'''
        <footer>
            <p>AI股神团队分析报告 | 生成时间: {self.created_at}</p>
            <p style="margin-top: 0.5rem; font-size: 0.75rem;">
                ⚠️ 免责声明：本报告仅供研究参考，不构成投资建议。投资有风险，决策需谨慎。
            </p>
        </footer>'''
    
    def _generate_scripts(self) -> str:
        return '''<script>
        // Smooth scroll for TOC links
        document.querySelectorAll('a[href^="#"]').forEach(anchor => {
            anchor.addEventListener('click', function (e) {
                e.preventDefault();
                document.querySelector(this.getAttribute('href')).scrollIntoView({
                    behavior: 'smooth'
                });
            });
        });
        
        // Intersection Observer for animations
        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.style.opacity = '1';
                    entry.target.style.transform = 'translateY(0)';
                }
            });
        }, { threshold: 0.1 });
        
        document.querySelectorAll('.section').forEach(section => {
            section.style.opacity = '0';
            section.style.transform = 'translateY(20px)';
            section.style.transition = 'opacity 0.6s ease, transform 0.6s ease';
            observer.observe(section);
        });
        </script>'''

    def _markdown_to_html(self, text: str) -> str:
        """简单的Markdown转HTML（实现见 report_markdown.markdown_to_html）。"""
        return markdown_to_html(text)

    def save(self, filepath: Optional[str] = None) -> str:
        """保存HTML报告到文件"""
        if filepath is None:
            filepath = f"reports/{self.session_id}.html"

        # 仅当路径含目录时才创建：裸文件名（如 "report.html"）的 dirname 为空串，
        # 直接 makedirs("") 会抛 FileNotFoundError。
        parent = os.path.dirname(filepath)
        if parent:
            os.makedirs(parent, exist_ok=True)

        html = self.generate()
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(html)

        return filepath


